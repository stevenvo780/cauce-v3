def account_identity(host: str, systemd_user: str) -> tuple[int, pathlib.Path]:
    key = (host, systemd_user)
    cached = _ACCOUNT_CACHE.get(key)
    if cached is not None:
        return cached
    if os.environ.get("CAUCE_WRITER_TEST_MODE") == "1":
        test_uid = os.environ.get("CAUCE_WRITER_TEST_ACCOUNT_UID", "")
        test_home = os.environ.get("CAUCE_WRITER_TEST_ACCOUNT_HOME", "")
        if re.fullmatch(r"[0-9]+", test_uid) is None or not test_home:
            fail("writer-state test account identity is incomplete")
        uid = int(test_uid)
        home = pathlib.Path(test_home)
    elif host == "local":
        try:
            account = pwd.getpwnam(systemd_user)
        except KeyError as error:
            raise WriterStateError(
                "declared systemd user does not exist on its local host"
            ) from error
        uid = account.pw_uid
        home = pathlib.Path(account.pw_dir)
    else:
        completed = run_host_command(
            [*ssh_prefix(host, systemd_user), "/usr/bin/python3", "-", systemd_user],
            label=f"systemd account inventory for host {host}",
            input_text=REMOTE_ACCOUNT_QUERY,
        )
        try:
            document = json.loads(completed.stdout)
        except json.JSONDecodeError as error:
            raise WriterStateError(
                "remote systemd account inventory is invalid"
            ) from error
        if not isinstance(document, dict) or set(document) != {"home", "uid"}:
            fail("remote systemd account inventory is invalid")
        uid = document["uid"]
        home = (
            pathlib.Path(document["home"])
            if isinstance(document["home"], str)
            else pathlib.Path()
        )
    if not isinstance(uid, int) or uid < 0:
        fail("declared systemd account UID is invalid")
    pure_home = pathlib.PurePosixPath(os.fspath(home))
    if (
        not home.is_absolute()
        or str(pure_home) != os.fspath(home)
        or ".." in pure_home.parts
    ):
        fail("declared systemd account home is invalid")
    _ACCOUNT_CACHE[key] = (uid, home)
    return uid, home


def clean_user_environment(
    systemd_user: str, uid: int, home: pathlib.Path
) -> list[str]:
    runtime = f"/run/user/{uid}"
    return [
        "/usr/bin/env",
        "-i",
        f"PATH={SYSTEM_PATH}",
        f"HOME={home}",
        f"USER={systemd_user}",
        f"LOGNAME={systemd_user}",
        "LC_ALL=C",
        f"XDG_RUNTIME_DIR={runtime}",
        f"DBUS_SESSION_BUS_ADDRESS=unix:path={runtime}/bus",
    ]


def systemctl_command(
    host: str,
    systemd_user: str,
    scope: str,
    arguments: list[str],
    *,
    mutating: bool = False,
) -> list[str]:
    if scope not in {"system", "user"}:
        fail("writer systemd scope is invalid")
    systemctl = tool_path("CAUCE_WRITER_TEST_SYSTEMCTL", "/usr/bin/systemctl")
    command = [systemctl, *(["--user"] if scope == "user" else []), *arguments]
    if scope == "user":
        uid, home = account_identity(host, systemd_user)
        command = [*clean_user_environment(systemd_user, uid, home), *command]
    if host == "local":
        if scope == "user":
            uid, _home = account_identity(host, systemd_user)
            if os.geteuid() == uid:
                return command
            if os.geteuid() == 0:
                return ["/usr/sbin/runuser", "-u", systemd_user, "--", *command]
            return ["/usr/bin/sudo", "-n", "-u", systemd_user, "--", *command]
        if mutating and os.geteuid() != 0:
            return ["/usr/bin/sudo", "-n", "--", *command]
        return command
    remote = command
    if mutating and scope == "system":
        remote = ["/usr/bin/sudo", "-n", "--", *remote]
    return [*ssh_prefix(host, systemd_user), *remote]


def run_host_command(
    command: list[str],
    *,
    label: str,
    input_text: str | None = None,
) -> subprocess.CompletedProcess[str]:
    try:
        completed = subprocess.run(
            command,
            check=False,
            text=True,
            capture_output=True,
            input=input_text,
            timeout=30,
        )
    except (OSError, subprocess.TimeoutExpired) as error:
        raise WriterStateError(f"{label} is unavailable") from error
    if completed.returncode != 0:
        fail(f"{label} is unavailable")
    return completed


def systemctl_show(
    host: str,
    systemd_user: str,
    scope: str,
    units: list[str],
) -> dict[str, dict[str, str]]:
    command = systemctl_command(
        host,
        systemd_user,
        scope,
        [
            "show",
            "--no-pager",
            "--property=Id,LoadState,UnitFileState,ActiveState,SubState,MainPID,FragmentPath,DropInPaths,NeedDaemonReload",
            *units,
        ],
    )
    completed = run_host_command(
        command,
        label=f"{scope} systemd manager inventory for host {host}",
    )
    if not completed.stdout.strip():
        fail(
            f"{scope} systemd manager could not inventory the declared writer units on host {host}"
        )
    return parse_show(completed.stdout, units)


