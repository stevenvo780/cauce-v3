def read_json_bytes(content: bytes, label: str) -> dict[str, Any]:
    try:
        decoded = content.decode("utf-8")
        value = json.loads(decoded)
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise WriterStateError(f"{label} is not canonical JSON") from error
    return object_value(value, label)


def private_file(path: pathlib.Path, *, label: str, mode: int = 0o600) -> bytes:
    if not path.is_absolute():
        fail(f"{label} path must be absolute")
    try:
        before = path.lstat()
    except OSError as error:
        raise WriterStateError(f"{label} is unavailable") from error
    if (
        not stat.S_ISREG(before.st_mode)
        or stat.S_ISLNK(before.st_mode)
        or before.st_nlink != 1
        or stat.S_IMODE(before.st_mode) != mode
        or before.st_uid not in {0, os.geteuid()}
    ):
        fail(f"{label} must be an owned single-link mode-{mode:04o} regular file")
    flags = os.O_RDONLY | os.O_CLOEXEC
    if hasattr(os, "O_NOFOLLOW"):
        flags |= os.O_NOFOLLOW
    descriptor = os.open(path, flags)
    try:
        opened = os.fstat(descriptor)
        chunks: list[bytes] = []
        while True:
            chunk = os.read(descriptor, 1024 * 1024)
            if not chunk:
                break
            chunks.append(chunk)
        after = os.fstat(descriptor)
    finally:
        os.close(descriptor)

    def signature(item: os.stat_result) -> tuple[int, ...]:
        return (
            item.st_dev,
            item.st_ino,
            item.st_mode,
            item.st_nlink,
            item.st_uid,
            item.st_gid,
            item.st_size,
            item.st_mtime_ns,
            item.st_ctime_ns,
        )

    if signature(before) != signature(opened) or signature(opened) != signature(after):
        fail(f"{label} changed while it was read")
    return b"".join(chunks)


def authenticated_transition_lock() -> int:
    """Retain and authenticate the release lock for every state mutation.

    The descriptor/token pair is minted only by ``pin-production-release.py
    locked-exec``.  Checking the named inode, exact capability bytes and an
    independently opened non-blocking probe prevents a caller from supplying an
    arbitrary readable descriptor or a stale lock file.
    """
    env_raw = os.environ.get("CAUCE_ENV_FILE", "")
    descriptor_raw = os.environ.get("CAUCE_RELEASE_TRANSITION_LOCK_FD", "")
    token = os.environ.get("CAUCE_RELEASE_TRANSITION_LOCK_TOKEN", "")
    if not env_raw or not pathlib.Path(env_raw).is_absolute():
        fail("production env is required to authenticate writer-state mutation")
    if re.fullmatch(r"[0-9]+", descriptor_raw) is None or int(descriptor_raw) < 3:
        fail("writer-state mutation lacks an inherited release lock descriptor")
    if re.fullmatch(r"[a-f0-9]{64}", token) is None:
        fail("writer-state mutation lacks an inherited release lock capability")

    env_path = pathlib.Path(env_raw)
    try:
        env_metadata = env_path.lstat()
    except OSError as error:
        raise WriterStateError(
            "production env is unavailable for writer-state mutation"
        ) from error
    if (
        not stat.S_ISREG(env_metadata.st_mode)
        or stat.S_ISLNK(env_metadata.st_mode)
        or env_metadata.st_nlink != 1
        or stat.S_IMODE(env_metadata.st_mode) != 0o600
        or env_metadata.st_uid not in {0, os.geteuid()}
    ):
        fail("production env is unsafe for writer-state mutation")

    lock_path = env_path.parent / f".{env_path.name}.release-pin.lock"
    try:
        descriptor = os.dup(int(descriptor_raw))
        opened = os.fstat(descriptor)
        named = lock_path.lstat()
    except OSError as error:
        raise WriterStateError(
            "writer-state inherited release lock is unavailable"
        ) from error
    try:
        if (
            (opened.st_dev, opened.st_ino) != (named.st_dev, named.st_ino)
            or not stat.S_ISREG(opened.st_mode)
            or opened.st_nlink != 1
            or stat.S_IMODE(opened.st_mode) != 0o600
            or opened.st_uid not in {0, os.geteuid()}
        ):
            fail("writer-state inherited release lock identity is invalid")
        if os.pread(descriptor, 65, 0) != f"{token}\n".encode("ascii"):
            fail("writer-state inherited release lock capability does not match")

        flags = os.O_RDWR | os.O_CLOEXEC
        if hasattr(os, "O_NOFOLLOW"):
            flags |= os.O_NOFOLLOW
        probe = os.open(lock_path, flags)
        try:
            try:
                fcntl.flock(probe, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError:
                pass
            else:
                fcntl.flock(probe, fcntl.LOCK_UN)
                fail("writer-state inherited release flock was not already exclusive")

            if not ofd_lock_conflicts(probe):
                fail(
                    "writer-state inherited release OFD lock was not already exclusive"
                )

            if ofd_lock_conflicts(descriptor):
                fail(
                    "writer-state inherited release lock is not owned by this transition"
                )

            try:
                fcntl.flock(probe, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError:
                pass
            else:
                fcntl.flock(probe, fcntl.LOCK_UN)
                fail("writer-state inherited release flock ownership was lost")
            if not ofd_lock_conflicts(probe):
                fail("writer-state inherited release OFD ownership was lost")
        finally:
            os.close(probe)
        return descriptor
    except Exception:
        os.close(descriptor)
        raise


def load_snapshot(
    path: pathlib.Path,
    expected_sha256: str,
    ops_root: pathlib.Path | None = None,
) -> dict[str, Any]:
    if DIGEST_RE.fullmatch(expected_sha256) is None:
        fail("writer snapshot SHA-256 is invalid")
    content = private_file(path, label="writer snapshot")
    if sha256_bytes(content) != expected_sha256:
        fail("writer snapshot differs from its selected SHA-256")
    snapshot = read_json_bytes(content, "writer snapshot")
    validate_snapshot(snapshot, ops_root)
    canonical = (
        json.dumps(snapshot, sort_keys=True, separators=(",", ":")) + "\n"
    ).encode()
    if content != canonical:
        fail("writer snapshot bytes are not canonical")
    return snapshot


def manifest_aliases(ops_root: pathlib.Path) -> dict[str, dict[str, str]]:
    source = ops_root / "container-aliases.json"
    document = read_json_bytes(source.read_bytes(), "container alias manifest")
    if set(document) != {
        "schemaVersion",
        "systemPrincipals",
        "historicalAliases",
        "aliases",
    }:
        fail("container alias manifest has unexpected fields")
    if document.get("schemaVersion") != 2:
        fail("container alias manifest schemaVersion is unsupported")
    try:
        aliases = load_container_aliases(ops_root)
    except (ContainerAliasError, json.JSONDecodeError, OSError) as error:
        raise WriterStateError("container alias manifest is invalid") from error
    result: dict[str, dict[str, str]] = {}
    for alias, body in aliases.items():
        tenant = body["tenant"]
        host = body.get("dockerHost", "local")
        systemd_user = body.get("systemdUser")
        if not isinstance(systemd_user, str) or USER_RE.fullmatch(systemd_user) is None:
            fail(f"alias {alias} must declare an exact systemd user")
        result[alias] = {"host": host, "systemdUser": systemd_user, "tenant": tenant}
    return result


def checksum_manifest(directory: pathlib.Path) -> dict[str, str]:
    manifest = directory / "SHA256SUMS"
    entries: dict[str, str] = {}
    for raw in manifest.read_text(encoding="utf-8").splitlines():
        match = re.fullmatch(r"([a-f0-9]{64})  ([A-Za-z0-9._/-]+)", raw)
        if (
            match is None
            or match.group(2).startswith("/")
            or ".." in pathlib.PurePosixPath(match.group(2)).parts
        ):
            fail(f"invalid generated-unit checksum manifest: {manifest}")
        name = match.group(2)
        if name in entries:
            fail(f"duplicate generated-unit checksum entry: {name}")
        entries[name] = match.group(1)
    if not entries:
        fail(f"generated-unit checksum manifest is empty: {manifest}")
    return entries


def generated_units(
    ops_root: pathlib.Path,
    aliases: dict[str, dict[str, str]],
) -> dict[tuple[str, str], str]:
    families = {
        "host-native": (
            "system",
            ops_root / "generated" / "systemd",
            "cauce-v3-alias-{}.service",
        ),
        "container-system": (
            "system",
            ops_root / "generated" / "container-systemd",
            "cauce-v3-container-{}.service",
        ),
        "container-rootless": (
            "user",
            ops_root / "generated" / "container-systemd" / "rootless",
            "cauce-v3-container-{}.service",
        ),
    }
    result: dict[tuple[str, str], str] = {}
    for family, (_scope, directory, template) in families.items():
        checksums = checksum_manifest(directory)
        for alias in aliases:
            name = template.format(alias)
            path = directory / name
            expected = checksums.get(name)
            if expected is None or not path.is_file() or path.is_symlink():
                fail(
                    f"generated unit is absent from its exact checksum manifest: {family}/{name}"
                )
            observed = hashlib.sha256(path.read_bytes()).hexdigest()
            if observed != expected:
                fail(
                    f"generated unit differs from its checksum manifest: {family}/{name}"
                )
            # Preserve the authenticated content identity, never the pathname:
            # systemctl inventory is remote and can take long enough for an
            # otherwise valid source path to be replaced underneath us.
            result[(family, alias)] = f"sha256:{observed}"
    return result


def parse_show(output: str, expected: list[str]) -> dict[str, dict[str, str]]:
    records: dict[str, dict[str, str]] = {}
    for block in re.split(r"\n\s*\n", output.strip()):
        if not block.strip():
            continue
        values: dict[str, str] = {}
        for raw in block.splitlines():
            if "=" not in raw:
                fail("systemd unit inventory returned a malformed property")
            key, value = raw.split("=", 1)
            if key in values:
                fail("systemd unit inventory returned a duplicate property")
            values[key] = value
        unit = values.get("Id", "")
        if unit not in expected or unit in records:
            fail("systemd unit inventory returned an unexpected or duplicate unit")
        records[unit] = values
    if set(records) != set(expected):
        fail("systemd unit inventory omitted a declared unit")
    return records


def ssh_prefix(host: str, systemd_user: str) -> list[str]:
    if HOST_RE.fullmatch(host) is None or USER_RE.fullmatch(systemd_user) is None:
        fail("writer host routing identity is invalid")
    return [
        tool_path("CAUCE_WRITER_TEST_SSH", "/usr/bin/ssh"),
        "-o",
        "BatchMode=yes",
        "-o",
        "ConnectTimeout=10",
        "--",
        f"{systemd_user}@{host}",
    ]


