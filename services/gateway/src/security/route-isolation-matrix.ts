export type RouteIsolationMethod = 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE' | 'HEAD' | 'OPTIONS';
export type RouteIsolationKind = 'public' | 'scoped' | 'actor' | 'host' | 'websocket';

export interface RouteIsolationProbe {
  readonly url: string;
  readonly payload?: unknown;
  readonly expectedStatus?: readonly number[];
}

export interface RouteIsolationEntry {
  readonly method: RouteIsolationMethod;
  readonly url: string;
  readonly kind: RouteIsolationKind;
  readonly reason: string;
  readonly probe?: RouteIsolationProbe;
  readonly errorMessageEcho?: string;
}

const DENIED = [403, 404] as const;
const REQUEST_ID = '11111111-1111-4111-8111-111111111111';
const CROSS_TENANT = 'El recurso pertenece a B; el dueño autenticado de A debe recibir una denegación.';
const ACTOR_SCOPE = 'La identidad y la empresa se obtienen de la sesión; la respuesta debe excluir los recursos de B.';
const HOST_SCOPE = 'La ruta exige identidad de host firmada y rechaza la cookie de una sesión humana.';

function scoped(method: RouteIsolationMethod, url: string, target: string, payload?: unknown): RouteIsolationEntry {
  return { method, url, kind: 'scoped', reason: CROSS_TENANT,
    probe: { url: target, ...(payload === undefined ? {} : { payload }), expectedStatus: DENIED } };
}

function actor(method: RouteIsolationMethod, url: string, reason = ACTOR_SCOPE, probe?: RouteIsolationProbe): RouteIsolationEntry {
  const effectiveProbe = probe ?? (method === 'GET' ? { url, expectedStatus: [200] } : undefined);
  return { method, url, kind: 'actor', reason, ...(effectiveProbe === undefined ? {} : { probe: effectiveProbe }) };
}

function host(method: RouteIsolationMethod, url: string, target: string): RouteIsolationEntry {
  return { method, url, kind: 'host', reason: HOST_SCOPE, probe: { url: target, payload: {}, expectedStatus: DENIED } };
}

function publicRoute(method: RouteIsolationMethod, url: string, reason: string): RouteIsolationEntry {
  return { method, url, kind: 'public', reason };
}

